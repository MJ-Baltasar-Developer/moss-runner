#!/bin/sh
# Build the Rust engine to WebAssembly into web/pkg, and the offline file list for the service worker.
# Needs: Rust (https://rustup.rs) with the wasm32 target, and wasm-pack.
#   rustup target add wasm32-unknown-unknown
#   cargo install wasm-pack
set -e
cd "$(dirname "$0")"
wasm-pack build engine --target web --out-dir ../web/pkg --release --no-pack

# web/sw-files.js: every file the game needs offline, and a version that changes when any of them does
cd web
FILES=$(find . -type f ! -name '.*' ! -name 'sw.js' ! -name 'sw-files.js' ! -name '*.d.ts' | sed 's|^\./||' | sort)  # hidden files aren't published by GitHub Pages
VERSION=$(cat $FILES | sha256sum | cut -c1-12)
{
  echo "// Generated by build.sh. Do not edit."
  echo "self.MOSS_VERSION = '$VERSION';"
  echo "self.MOSS_FILES = ['./',"
  for f in $FILES; do echo "  './$f',"; done
  echo "];"
} > sw-files.js
echo "Built web/pkg and web/sw-files.js (version $VERSION)."
echo "Serve the web folder, e.g.: python3 -m http.server 8000 --directory web"
